// Writes src/app/core/api-base.ts from CORPORATE_API_URL (e.g. https://ariyoo-corporate-api.onrender.com).
import { writeFileSync } from 'node:fs';
const url = (process.env.CORPORATE_API_URL || '').replace(/\/+$/, '');
if (!/^https?:\/\/[^\s]+$/.test(url)) {
  console.error('Set CORPORATE_API_URL to the API address, for example https://api.example.com');
  process.exit(1);
}
writeFileSync(new URL('../src/app/core/api-base.ts', import.meta.url),
`/** Generated by scripts/set-api-url.mjs. Do not edit by hand. */\nexport const API_BASE = '${url}/api';\n`);
console.log('API base set to', `${url}/api`);
