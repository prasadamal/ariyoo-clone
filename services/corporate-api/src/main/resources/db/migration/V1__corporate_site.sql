-- Messages sent through the website's contact form.
CREATE TABLE contact_message (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(120)  NOT NULL,
    email       VARCHAR(254)  NOT NULL,
    topic       VARCHAR(30)   NOT NULL,
    organisation VARCHAR(160),
    message     VARCHAR(4000) NOT NULL,
    created_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX contact_message_created_idx ON contact_message (created_at DESC);

-- Newsletter. Not confirmed until the person follows the link (double opt-in is wired once email sending is).
CREATE TABLE newsletter_subscriber (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email       VARCHAR(254) NOT NULL UNIQUE,
    token       VARCHAR(64)  NOT NULL UNIQUE,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    unsubscribed_at TIMESTAMP
);

-- Open roles. Empty until the team publishes one.
CREATE TABLE job (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug        VARCHAR(80)  NOT NULL UNIQUE,
    title       VARCHAR(160) NOT NULL,
    team        VARCHAR(80)  NOT NULL,
    location    VARCHAR(120) NOT NULL,
    employment  VARCHAR(40)  NOT NULL,
    summary     VARCHAR(2000) NOT NULL,
    published   BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- job_id is empty for an open application.
CREATE TABLE job_application (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id      BIGINT REFERENCES job (id) ON DELETE SET NULL,
    name        VARCHAR(120)  NOT NULL,
    email       VARCHAR(254)  NOT NULL,
    profile_url VARCHAR(500),
    message     VARCHAR(4000) NOT NULL,
    created_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX job_application_created_idx ON job_application (created_at DESC);

-- Press releases and company news. Empty until something is published.
CREATE TABLE press_item (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug        VARCHAR(100)  NOT NULL UNIQUE,
    title       VARCHAR(200)  NOT NULL,
    summary     VARCHAR(500)  NOT NULL,
    body        VARCHAR(20000) NOT NULL,
    published_at TIMESTAMP    NOT NULL
);
CREATE INDEX press_item_published_idx ON press_item (published_at DESC);
